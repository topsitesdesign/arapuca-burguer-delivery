-- Tabelas do sistema em PostgreSQL (Supabase), equivalentes às de site/app/sql/schema.sql (MySQL).
-- Dinheiro em centavos (INTEGER); datas em milissegundos desde 1970 (BIGINT, UTC). Sim/não fica 0/1 (SMALLINT), como no MySQL.
-- O instalador roda este arquivo sozinho. Já sai na versão 3 do banco (as migrações 2 e 3 do MySQL estão incluídas).

CREATE TABLE IF NOT EXISTS configuracoes (
  chave VARCHAR(40) NOT NULL PRIMARY KEY,
  valor TEXT NOT NULL,
  atualizado_em BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS usuarios (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  email VARCHAR(120) NOT NULL,
  telefone VARCHAR(20) NOT NULL DEFAULT '',
  senha_hash VARCHAR(255) NOT NULL,
  funcao VARCHAR(20) NOT NULL,
  permissoes VARCHAR(255) NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'ativo',
  ultimo_acesso BIGINT NULL,
  ordem INTEGER NOT NULL DEFAULT 0,
  criado_em BIGINT NOT NULL,
  totp_segredo VARCHAR(160) NULL,
  totp_ativo SMALLINT NOT NULL DEFAULT 0,
  totp_passo BIGINT NOT NULL DEFAULT 0,
  totp_recuperacao TEXT NULL,
  removido_em BIGINT NULL,
  CONSTRAINT uq_usuarios_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS categorias (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  nome VARCHAR(60) NOT NULL,
  descricao VARCHAR(200) NOT NULL DEFAULT '',
  icone VARCHAR(20) NOT NULL DEFAULT '',
  imagem VARCHAR(40) NOT NULL DEFAULT '',
  ativa SMALLINT NOT NULL DEFAULT 1,
  especial SMALLINT NOT NULL DEFAULT 0,
  ordem INTEGER NOT NULL DEFAULT 0,
  versao INTEGER NOT NULL DEFAULT 1,
  arquivado_em BIGINT NULL
);

CREATE TABLE IF NOT EXISTS produtos (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  categoria_id VARCHAR(60) NOT NULL,
  preco INTEGER NOT NULL,
  promo INTEGER NULL,
  descricao VARCHAR(400) NOT NULL DEFAULT '',
  ingredientes TEXT NOT NULL,
  grupos TEXT NOT NULL,
  preparo SMALLINT NOT NULL DEFAULT 12,
  codigo VARCHAR(20) NOT NULL DEFAULT '',
  ativo SMALLINT NOT NULL DEFAULT 1,
  destaque SMALLINT NOT NULL DEFAULT 0,
  esgotado SMALLINT NOT NULL DEFAULT 0,
  foto VARCHAR(40) NOT NULL DEFAULT '',
  imagem VARCHAR(40) NOT NULL DEFAULT '',
  alt VARCHAR(200) NOT NULL DEFAULT '',
  selo VARCHAR(30) NOT NULL DEFAULT '',
  ordem INTEGER NOT NULL DEFAULT 0,
  atualizado_em BIGINT NOT NULL DEFAULT 0,
  versao INTEGER NOT NULL DEFAULT 1,
  arquivado_em BIGINT NULL
);
CREATE INDEX IF NOT EXISTS ix_produtos_categoria ON produtos (categoria_id);

CREATE TABLE IF NOT EXISTS grupos (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  nome VARCHAR(60) NOT NULL,
  obrigatorio SMALLINT NOT NULL DEFAULT 0,
  tipo VARCHAR(10) NOT NULL DEFAULT 'multiplo',
  min_escolhas SMALLINT NOT NULL DEFAULT 0,
  max_escolhas SMALLINT NOT NULL DEFAULT 1,
  ativo SMALLINT NOT NULL DEFAULT 1,
  opcoes TEXT NOT NULL,
  ordem INTEGER NOT NULL DEFAULT 0,
  versao INTEGER NOT NULL DEFAULT 1,
  arquivado_em BIGINT NULL
);

CREATE TABLE IF NOT EXISTS cupons (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL,
  tipo VARCHAR(12) NOT NULL,
  valor INTEGER NOT NULL DEFAULT 0,
  minimo INTEGER NOT NULL DEFAULT 0,
  usos INTEGER NOT NULL DEFAULT 0,
  limite INTEGER NULL,
  por_cliente INTEGER NOT NULL DEFAULT 1,
  inicio VARCHAR(10) NOT NULL DEFAULT '',
  validade VARCHAR(10) NOT NULL DEFAULT '',
  habilitado SMALLINT NOT NULL DEFAULT 1,
  descricao VARCHAR(200) NOT NULL DEFAULT '',
  ordem INTEGER NOT NULL DEFAULT 0,
  versao INTEGER NOT NULL DEFAULT 1,
  arquivado_em BIGINT NULL
);
CREATE INDEX IF NOT EXISTS ix_cupons_codigo ON cupons (codigo);

CREATE TABLE IF NOT EXISTS areas (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  nome VARCHAR(60) NOT NULL,
  taxa INTEGER NOT NULL DEFAULT 0,
  tempo_extra SMALLINT NOT NULL DEFAULT 0,
  minimo INTEGER NOT NULL DEFAULT 0,
  ativa SMALLINT NOT NULL DEFAULT 1,
  cobertura VARCHAR(10) NOT NULL DEFAULT 'raio',
  cep_ini VARCHAR(9) NOT NULL DEFAULT '',
  cep_fim VARCHAR(9) NOT NULL DEFAULT '',
  raio NUMERIC(5,1) NOT NULL DEFAULT 0,
  ordem INTEGER NOT NULL DEFAULT 0,
  versao INTEGER NOT NULL DEFAULT 1,
  arquivado_em BIGINT NULL
);

CREATE TABLE IF NOT EXISTS banners (
  id VARCHAR(60) NOT NULL PRIMARY KEY,
  titulo VARCHAR(80) NOT NULL,
  texto VARCHAR(200) NOT NULL DEFAULT '',
  foto VARCHAR(40) NOT NULL DEFAULT '',
  imagem VARCHAR(40) NOT NULL DEFAULT '',
  destino VARCHAR(100) NOT NULL DEFAULT '',
  inicio VARCHAR(10) NOT NULL DEFAULT '',
  fim VARCHAR(10) NOT NULL DEFAULT '',
  status VARCHAR(12) NOT NULL DEFAULT 'ativo',
  ordem INTEGER NOT NULL DEFAULT 0,
  desktop SMALLINT NOT NULL DEFAULT 1,
  mobile SMALLINT NOT NULL DEFAULT 1,
  versao INTEGER NOT NULL DEFAULT 1,
  arquivado_em BIGINT NULL
);

CREATE TABLE IF NOT EXISTS pedidos (
  numero INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  codigo VARCHAR(16) NOT NULL,
  chave_envio VARCHAR(32) NULL,
  status VARCHAR(12) NOT NULL,
  origem VARCHAR(10) NOT NULL DEFAULT 'site',
  cliente_nome VARCHAR(80) NOT NULL,
  cliente_telefone VARCHAR(11) NOT NULL,
  modalidade VARCHAR(10) NOT NULL,
  area_id VARCHAR(60) NULL,
  endereco TEXT NULL,
  itens TEXT NOT NULL,
  pagamento_forma VARCHAR(10) NOT NULL,
  troco_para INTEGER NULL,
  cupom_codigo VARCHAR(30) NULL,
  subtotal INTEGER NOT NULL,
  desconto INTEGER NOT NULL DEFAULT 0,
  taxa INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL,
  obs VARCHAR(300) NOT NULL DEFAULT '',
  prazo VARCHAR(30) NOT NULL DEFAULT '',
  agendado_para BIGINT NULL,
  usuario_id VARCHAR(60) NULL,
  criado_em BIGINT NOT NULL,
  atualizado_em BIGINT NOT NULL,
  rev BIGINT NOT NULL DEFAULT 0,
  pagamento_status VARCHAR(12) NOT NULL DEFAULT 'pendente',
  pagamento_valor INTEGER NULL,
  pagamento_real VARCHAR(10) NULL,
  pagamento_entregador VARCHAR(60) NOT NULL DEFAULT '',
  pagamento_usuario VARCHAR(60) NULL,
  pagamento_em BIGINT NULL,
  pagamento_obs VARCHAR(120) NOT NULL DEFAULT '',
  anonimizado_em BIGINT NULL,
  assinatura VARCHAR(40) NULL,
  CONSTRAINT uq_pedidos_codigo UNIQUE (codigo),
  CONSTRAINT uq_pedidos_chave UNIQUE (chave_envio)
);
CREATE INDEX IF NOT EXISTS ix_pedidos_criado ON pedidos (criado_em);
CREATE INDEX IF NOT EXISTS ix_pedidos_atualizado ON pedidos (atualizado_em);
CREATE INDEX IF NOT EXISTS ix_pedidos_status ON pedidos (status);
CREATE INDEX IF NOT EXISTS ix_pedidos_telefone ON pedidos (cliente_telefone);
CREATE INDEX IF NOT EXISTS ix_pedidos_rev ON pedidos (rev);
CREATE INDEX IF NOT EXISTS ix_pedidos_agendado ON pedidos (agendado_para);
CREATE INDEX IF NOT EXISTS ix_pedidos_pagamento ON pedidos (pagamento_em);

CREATE TABLE IF NOT EXISTS pedido_eventos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_numero INTEGER NOT NULL,
  status VARCHAR(12) NOT NULL,
  motivo VARCHAR(120) NOT NULL DEFAULT '',
  usuario_id VARCHAR(60) NULL,
  em BIGINT NOT NULL,
  CONSTRAINT fk_eventos_pedido FOREIGN KEY (pedido_numero) REFERENCES pedidos (numero) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_eventos_pedido ON pedido_eventos (pedido_numero);

CREATE TABLE IF NOT EXISTS cupom_usos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cupom_id VARCHAR(60) NOT NULL,
  telefone VARCHAR(11) NOT NULL,
  pedido_numero INTEGER NOT NULL,
  em BIGINT NOT NULL,
  endereco_chave VARCHAR(40) NOT NULL DEFAULT '',
  predio_chave VARCHAR(40) NOT NULL DEFAULT '',
  CONSTRAINT fk_usos_pedido FOREIGN KEY (pedido_numero) REFERENCES pedidos (numero) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_cupom_usos ON cupom_usos (cupom_id, telefone);
CREATE INDEX IF NOT EXISTS ix_usos_predio ON cupom_usos (cupom_id, predio_chave);

CREATE TABLE IF NOT EXISTS notificacoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  icone VARCHAR(20) NOT NULL DEFAULT 'receipt',
  cor VARCHAR(10) NOT NULL DEFAULT '',
  titulo VARCHAR(120) NOT NULL,
  texto VARCHAR(200) NOT NULL DEFAULT '',
  rota VARCHAR(30) NOT NULL DEFAULT 'pedidos',
  pedido INTEGER NULL,
  lida SMALLINT NOT NULL DEFAULT 0,
  em BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_notificacoes_em ON notificacoes (em);

CREATE TABLE IF NOT EXISTS tentativas (
  chave VARCHAR(40) NOT NULL PRIMARY KEY,
  contador INTEGER NOT NULL DEFAULT 0,
  inicio BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id VARCHAR(60) NULL,
  acao VARCHAR(40) NOT NULL,
  entidade VARCHAR(30) NOT NULL DEFAULT '',
  entidade_id VARCHAR(60) NOT NULL DEFAULT '',
  detalhes TEXT NULL,
  ip_hash VARCHAR(16) NOT NULL DEFAULT '',
  criado_em BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_auditoria_criado ON auditoria (criado_em);
CREATE INDEX IF NOT EXISTS ix_auditoria_acao ON auditoria (acao, criado_em);

CREATE TABLE IF NOT EXISTS pedido_itens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_numero INTEGER NOT NULL,
  linha SMALLINT NOT NULL DEFAULT 0,
  produto_id VARCHAR(60) NOT NULL DEFAULT '',
  nome VARCHAR(80) NOT NULL DEFAULT '',
  qtd SMALLINT NOT NULL DEFAULT 1,
  preco INTEGER NOT NULL DEFAULT 0,
  adicionais INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL DEFAULT 0,
  opcoes VARCHAR(400) NOT NULL DEFAULT '',
  obs VARCHAR(140) NOT NULL DEFAULT '',
  criado_em BIGINT NOT NULL,
  CONSTRAINT fk_itens_pedido FOREIGN KEY (pedido_numero) REFERENCES pedidos (numero) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_itens_pedido ON pedido_itens (pedido_numero);
CREATE INDEX IF NOT EXISTS ix_itens_produto ON pedido_itens (produto_id, criado_em);
CREATE INDEX IF NOT EXISTS ix_itens_criado ON pedido_itens (criado_em);

CREATE TABLE IF NOT EXISTS contadores (
  nome VARCHAR(20) NOT NULL PRIMARY KEY,
  valor BIGINT NOT NULL DEFAULT 0
);
INSERT INTO contadores (nome, valor) VALUES ('rev', 0) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS bloqueados (
  telefone VARCHAR(11) NOT NULL PRIMARY KEY,
  motivo VARCHAR(120) NOT NULL DEFAULT '',
  usuario_id VARCHAR(60) NULL,
  criado_em BIGINT NOT NULL
);

-- sessões do painel e do site (na Vercel não há arquivos de sessão)
CREATE TABLE IF NOT EXISTS sessoes (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  dados TEXT NOT NULL,
  expira BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_sessoes_expira ON sessoes (expira);

-- Supabase: as tabelas não ficam abertas para a API pública (o sistema não usa a API REST do Supabase).
-- RLS ligado e nenhuma política para anon/authenticated: só a conexão do servidor (dona das tabelas) lê e grava.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['configuracoes','usuarios','categorias','produtos','grupos','cupons','areas','banners','pedidos','pedido_eventos',
    'cupom_usos','notificacoes','tentativas','auditoria','pedido_itens','contadores','bloqueados','sessoes'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
